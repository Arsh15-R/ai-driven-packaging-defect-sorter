from abc import ABC, abstractmethod
from typing import Dict, Any, Literal
from pydantic import BaseModel, Field


class InspectionResult(BaseModel):
    """
    Standardized inspection result schema across all model implementations.
    """
    prediction: Literal["Defective", "Non-defective"] = Field(
        ...,
        description="Binary classification verdict: 'Defective' or 'Non-defective'"
    )
    is_defective: bool = Field(
        ...,
        description="Boolean flag: True if defective, False if non-defective"
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Confidence score bounded between 0.0 and 1.0"
    )
    is_placeholder: bool = Field(
        ...,
        description="True if generated by a demo/placeholder heuristic, False for trained models"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Detailed metadata including model name, latency, detected defects, and coordinates"
    )

    def to_dict(self) -> Dict[str, Any]:
        """Convert result to standard dictionary."""
        return self.model_dump()


class BaseInspectionModel(ABC):
    """
    Abstract Base Class for product defect inspection models.
    
    Subclasses must implement the `predict` method taking raw image bytes
    and returning a dictionary conforming to the standard inspection result schema.
    """

    @abstractmethod
    def predict(self, image_bytes: bytes) -> Dict[str, Any]:
        """
        Execute defect classification on an input image.

        Args:
            image_bytes: Raw binary bytes of the image (JPEG, PNG, etc.).

        Returns:
            Dict[str, Any] containing:
                - 'prediction': 'Defective' | 'Non-defective'
                - 'is_defective': bool
                - 'confidence': float (0.0 to 1.0)
                - 'is_placeholder': bool
                - 'metadata': dict with model name, latency, defect specifics
        """
        pass

    @abstractmethod
    def get_info(self) -> Dict[str, Any]:
        """
        Return diagnostic metadata about the model (name, architecture, device, weights).
        """
        pass

    @staticmethod
    def validate_result(data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Validates and standardizes the result dictionary against the InspectionResult schema.
        """
        # Ensure prediction is exact string
        is_defective = bool(data.get("is_defective", False))
        prediction = data.get("prediction")
        if prediction not in ("Defective", "Non-defective"):
            prediction = "Defective" if is_defective else "Non-defective"

        raw_conf = float(data.get("confidence", 0.0))
        confidence = max(0.0, min(1.0, round(raw_conf, 4)))

        is_placeholder = bool(data.get("is_placeholder", False))
        metadata = data.get("metadata", {})
        if not isinstance(metadata, dict):
            metadata = {"raw_metadata": str(metadata)}

        validated = InspectionResult(
            prediction=prediction,
            is_defective=is_defective,
            confidence=confidence,
            is_placeholder=is_placeholder,
            metadata=metadata
        )
        return validated.to_dict()
